#include "../philo_bonus.h"

void	ft_strcat(char *des, const char *src)
{
	int	i;
	int	j;

	i = 0;
	j = 0;
	while (des[i] != '\0')
		i += 1;
	while (src[j] != '\0')
	{
		des[i + j] = src[j];
		j += 1;
	}
	des[i + j] = '\0';
}
